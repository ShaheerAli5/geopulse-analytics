import { InvestigationResponse } from "@/types/investigation";

function formatCoordStr(lat: number, lon: number): string {
  const latDir = lat >= 0 ? "N" : "S";
  const lonDir = lon >= 0 ? "E" : "W";
  return `${Math.abs(lat).toFixed(2)}°${latDir}, ${Math.abs(lon).toFixed(2)}°${lonDir}`;
}

export function generateInvestigationMarkdown(data: InvestigationResponse): string {
  const regA = data.region_a;
  const regB = data.region_b;

  const coordStrA = formatCoordStr(regA.region.lat, regA.region.lon);
  const coordStrB = regB ? formatCoordStr(regB.region.lat, regB.region.lon) : "N/A";

  const statsA = regA.stats;
  const statsB = regB?.stats;

  const md = `# GeoPulse Analytics — Earth System Trend Detective Report
**Investigation ID:** \`${data.investigation_id}\`  
**Generated Date:** ${new Date().toISOString()}  
**NASA Variable:** ${data.variable_name} (\`${data.variable_id}\`)  
**Units:** ${data.units}  
**Aggregation Mode:** ${data.aggregation_mode}  
**Temporal Window:** ${data.start_year} – ${data.end_year}  

---

## 1. Executive Summary & Verdict
**${data.ai_interpretation.headline}**

- **What is Changing:** ${data.ai_interpretation.what_is_changing}
- **Regional Divergence:** ${data.ai_interpretation.where_it_diverges}
- **Statistical Significance:** ${data.ai_interpretation.statistical_verdict}
- **Limitations & Caveats:** ${data.ai_interpretation.limitations_and_caveats}

---

## 2. Comparative Statistical Scorecard

| Statistical Metric | Region A: ${regA.region.name} (${coordStrA}) | ${regB ? `Region B: ${regB.region.name} (${coordStrB})` : "Region B: None"} |
| :--- | :--- | :--- |
| **Confidence Badge** | \`${statsA.badge}\` | ${statsB ? `\`${statsB.badge}\`` : "N/A"} |
| **OLS Slope (/decade)** | ${statsA.ols_slope_per_decade >= 0 ? "+" : ""}${statsA.ols_slope_per_decade.toFixed(4)} ${data.units}/decade | ${statsB ? `${statsB.ols_slope_per_decade >= 0 ? "+" : ""}${statsB.ols_slope_per_decade.toFixed(4)} ${data.units}/decade` : "N/A"} |
| **Sen's Robust Slope (/decade)** | ${statsA.sen_slope_per_decade >= 0 ? "+" : ""}${statsA.sen_slope_per_decade.toFixed(4)} ${data.units}/decade | ${statsB ? `${statsB.sen_slope_per_decade >= 0 ? "+" : ""}${statsB.sen_slope_per_decade.toFixed(4)} ${data.units}/decade` : "N/A"} |
| **Mann–Kendall p-value** | ${statsA.mk_p_value.toFixed(4)} (${statsA.mk_p_value < 0.05 ? "Significant p < 0.05" : "Not Significant p ≥ 0.05"}) | ${statsB ? `${statsB.mk_p_value.toFixed(4)} (${statsB.mk_p_value < 0.05 ? "Significant p < 0.05" : "Not Significant p ≥ 0.05"})` : "N/A"} |
| **Kendall's τ (Z-score)** | τ = ${statsA.mk_tau.toFixed(3)} (Z = ${statsA.mk_z_score.toFixed(2)}) | ${statsB ? `τ = ${statsB.mk_tau.toFixed(3)} (Z = ${statsB.mk_z_score.toFixed(2)})` : "N/A"} |
| **OLS 95% Confidence Interval** | [${statsA.ols_ci_lower_decade.toFixed(4)}, ${statsA.ols_ci_upper_decade.toFixed(4)}] | ${statsB ? `[${statsB.ols_ci_lower_decade.toFixed(4)}, ${statsB.ols_ci_upper_decade.toFixed(4)}]` : "N/A"} |
| **Sen's 95% Confidence Interval** | [${statsA.sen_ci_lower_decade.toFixed(4)}, ${statsA.sen_ci_upper_decade.toFixed(4)}] | ${statsB ? `[${statsB.sen_ci_lower_decade.toFixed(4)}, ${statsB.sen_ci_upper_decade.toFixed(4)}]` : "N/A"} |
| **OLS R²** | ${statsA.ols_r_squared.toFixed(4)} | ${statsB ? statsB.ols_r_squared.toFixed(4) : "N/A"} |
| **Lag-1 Autocorrelation** | ${statsA.lag1_autocorrelation.toFixed(3)} | ${statsB ? statsB.lag1_autocorrelation.toFixed(3) : "N/A"} |
| **Sample Size** | ${statsA.n_years} annual observations | ${statsB ? `${statsB.n_years} annual observations` : "N/A"} |

---

## 3. NASA Provenance & Data Pipeline
- **Mission / Model:** ${data.provenance.mission_model}
- **Data Source:** ${data.provenance.source_name}
- **API Endpoint:** \`${data.provenance.api_endpoint}\`
- **Spatial Resolution:** ${data.provenance.spatial_resolution}
- **Missing Months Filtered:** ${data.provenance.missing_months_filtered}
- **Retrieved At (UTC):** ${data.provenance.retrieved_at_utc}

### Verification Links:
${data.provenance.verification_links.map((l) => `- [${l.label}](${l.url})`).join("\n")}

---

*Report generated by GeoPulse Analytics — NASA Space Apps Challenge 2026 Submission.*
`;
  return md;
}

export function exportInvestigationMarkdown(data: InvestigationResponse): void {
  const content = generateInvestigationMarkdown(data);
  const blob = new Blob([content], { type: "text/markdown;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  const filename = `GeoPulse_Case_${data.variable_id}_${data.start_year}-${data.end_year}.md`;

  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function printInvestigationReport(): void {
  if (typeof window !== "undefined" && typeof window.print === "function") {
    window.print();
  }
}
